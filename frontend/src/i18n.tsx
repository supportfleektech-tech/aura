export const STRINGS = { en: EN, sw: SW };
export type TKey = keyof typeof EN;

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: TKey) => string }>({
  lang: "en",
  setLang: () => undefined,
  t: (k) => EN[k],
});

const detect = (): Lang => {
  try {
    const saved = localStorage.getItem("aura-lang");
    if (saved === "en" || saved === "sw") return saved;
    if ((navigator.language || "").toLowerCase().startsWith("sw")) return "sw";
  } catch { /* private mode */ }
  return "en";
};

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detect);
  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("aura-lang", l); } catch { /* ignore */ }
  };
  useEffect(() => { document.documentElement.lang = lang === "sw" ? "sw" : "en"; }, [lang]);
  const t = (k: TKey) => STRINGS[lang][k] ?? EN[k] ?? k;
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);
